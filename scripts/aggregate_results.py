#!/usr/bin/env python3
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

import json
import numpy as np

from src.utils import save_json

ROOT = os.path.join(os.path.dirname(__file__), "..")
OUT = os.path.join(ROOT, "research", "04_results")
os.makedirs(OUT, exist_ok=True)


def load(path):
    with open(os.path.join(ROOT, path), "r", encoding="utf-8") as f:
        return json.load(f)


def fmt_ci(x):
    return f"{x['mean']:.4f} ± {x['std']:.4f} [{x['ci_low']:.4f}, {x['ci_high']:.4f}]"


def main():
    summary = {}

    # Baselines
    try:
        b_sup = load("research/03_experiments/baselines_digits/supervised_results.json")
        b_con = load("research/03_experiments/baselines_digits/continual_results.json")
        summary["baselines_digits_supervised"] = {
            k: {"acc": v["acc"], "wall_s": v.get("wall_s"), "peak_rss_mb": v.get("peak_rss_mb")}
            for k, v in b_sup["results"].items()
        }
        summary["baselines_digits_continual"] = {
            k: {"AA": v["AA"], "FM": v["FM"], "wall_s": v.get("wall_s"), "peak_rss_mb": v.get("peak_rss_mb")}
            for k, v in b_con["results"].items()
        }
    except Exception as e:
        summary["baselines_error"] = str(e)

    # HSAM
    for name, path in [
        ("hsam_digits_supervised", "research/03_experiments/hsam_digits/supervised_results.json"),
        ("hsam_digits_continual", "research/03_experiments/hsam_digits/continual_results.json"),
    ]:
        try:
            d = load(path)
            if "supervised" in name:
                summary[name] = {k: {"acc": v["acc"], "config": v.get("config")} for k, v in d["results"].items()}
            else:
                summary[name] = {k: {"AA": v["AA"], "FM": v["FM"], "config": v.get("config")} for k, v in d["results"].items()}
        except Exception as e:
            summary[name + "_error"] = str(e)

    # Ablations
    try:
        a = load("research/03_experiments/hsam_ablations/results.json")
        summary["hsam_ablations_supervised"] = {k: {"acc": v["acc"], "config": v.get("config")} for k, v in a["supervised"].items()}
        summary["hsam_ablations_continual"] = {k: {"AA": v["AA"], "FM": v["FM"], "config": v.get("config")} for k, v in a["continual"].items()}
    except Exception as e:
        summary["hsam_ablations_error"] = str(e)

    # Stream
    try:
        s = load("research/03_experiments/hsam_self_improve_stream/results.json")
        summary["hsam_stream"] = {
            k: {"acc_first": v["acc_first"], "acc_last": v["acc_last"], "delta": v["delta"]}
            for k, v in s["results"].items()
        }
    except Exception as e:
        summary["hsam_stream_error"] = str(e)

    # Sanity
    try:
        san = load("research/03_experiments/sanity/overfit32_results.json")
        summary["sanity"] = san["results"]
    except Exception as e:
        summary["sanity_error"] = str(e)

    # Char
    try:
        c = load("research/03_experiments/char_csm/results.json")
        summary["char_csm"] = {
            k: {"acc_overall": v["acc_overall"], "acc_last20": v["acc_last20"], "acc_first20": v["acc_first20"]}
            for k, v in c["results"].items()
        }
    except Exception as e:
        summary["char_csm_error"] = str(e)

    save_json(os.path.join(OUT, "summary.json"), summary)

    # Markdown tables
    lines = []
    lines.append("# Aggregated Results (from saved JSON artifacts)\n")
    lines.append("Generated by `scripts/aggregate_results.py`. Values are mean ± std [95% bootstrap CI] over seeds recorded in each artifact. Claims remain subject to caveats in `research/FINAL_REPORT.md` and `research/novelty/assessment.md`.\n")

    if "baselines_digits_supervised" in summary:
        lines.append("## Digits supervised baselines\n")
        lines.append("| model | acc | wall_s mean | peak_rss_mb mean |\n|---|---:|---:|---:|")
        for k, v in summary["baselines_digits_supervised"].items():
            wall = v['wall_s']['mean'] if isinstance(v.get('wall_s'), dict) else float('nan')
            peak = v['peak_rss_mb']['mean'] if isinstance(v.get('peak_rss_mb'), dict) else float('nan')
            lines.append(f"| {k} | {fmt_ci(v['acc'])} | {wall:.4f} | {peak:.4f} |")
        lines.append("")

    if "baselines_digits_continual" in summary:
        lines.append("## Split-digits continual baselines\n")
        lines.append("| model | AA | FM | wall_s mean |\n|---|---:|---:|---:|")
        for k, v in summary["baselines_digits_continual"].items():
            wall = v['wall_s']['mean'] if isinstance(v.get('wall_s'), dict) else float('nan')
            lines.append(f"| {k} | {fmt_ci(v['AA'])} | {fmt_ci(v['FM'])} | {wall:.4f} |")
        lines.append("")

    if "hsam_digits_supervised" in summary:
        lines.append("## HSAM digits supervised\n")
        lines.append("| config | acc |\n|---|---:|")
        for k, v in summary["hsam_digits_supervised"].items():
            lines.append(f"| {k} | {fmt_ci(v['acc'])} |")
        lines.append("")

    if "hsam_digits_continual" in summary:
        lines.append("## HSAM split-digits continual\n")
        lines.append("| config | AA | FM |\n|---|---:|---:|")
        for k, v in summary["hsam_digits_continual"].items():
            lines.append(f"| {k} | {fmt_ci(v['AA'])} | {fmt_ci(v['FM'])} |")
        lines.append("")

    if "hsam_ablations_supervised" in summary:
        lines.append("## HSAM ablations - supervised\n")
        lines.append("| config | acc |\n|---|---:|")
        for k, v in summary["hsam_ablations_supervised"].items():
            lines.append(f"| {k} | {fmt_ci(v['acc'])} |")
        lines.append("")

    if "hsam_ablations_continual" in summary:
        lines.append("## HSAM ablations - continual\n")
        lines.append("| config | AA | FM |\n|---|---:|---:|")
        for k, v in summary["hsam_ablations_continual"].items():
            lines.append(f"| {k} | {fmt_ci(v['AA'])} | {fmt_ci(v['FM'])} |")
        lines.append("")

    if "hsam_stream" in summary:
        lines.append("## HSAM stream probe (self-improvement audit, limited)\n")
        lines.append("| mode | first acc | last acc | delta |\n|---|---:|---:|---:|")
        for k, v in summary["hsam_stream"].items():
            lines.append(f"| {k} | {fmt_ci(v['acc_first'])} | {fmt_ci(v['acc_last'])} | {fmt_ci(v['delta'])} |")
        lines.append("")
        lines.append("**Interpretation caution:** `no_tune` and `no_alloc` deltas are similar to `full` in this saved run, while `frozen_after_1` shows no improvement. This supports continued online learning vs freezing, but does **not** isolate an autonomous self-tuning/allocation benefit. [PRELIMINARY]\n")

    if "sanity" in summary:
        lines.append("## Sanity checks\n")
        for k, v in summary["sanity"].items():
            if isinstance(v, dict) and 'acc' in v:
                lines.append(f"- {k}: {fmt_ci(v['acc'])}")
        lines.append("")

    if "char_csm" in summary:
        lines.append("## Char stream CSM (exploratory)\n")
        lines.append("| variant | overall | first20 | last20 |\n|---|---:|---:|---:|")
        for k, v in summary["char_csm"].items():
            lines.append(f"| {k} | {fmt_ci(v['acc_overall'])} | {fmt_ci(v['acc_first20'])} | {fmt_ci(v['acc_last20'])} |")
        lines.append("")

    with open(os.path.join(OUT, "tables.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    # Simple plots (best-effort)
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        # Continual AA/FM comparison
        names = []
        aa = []
        fm = []
        for src in [("baselines_digits_continual", None), ("hsam_digits_continual", None)]:
            if src[0] in summary:
                for k, v in summary[src[0]].items():
                    names.append(k)
                    aa.append(v['AA']['mean'])
                    fm.append(v['FM']['mean'])
        if names:
            x = np.arange(len(names))
            fig, ax = plt.subplots(figsize=(max(8, len(names)*0.8), 4))
            ax.bar(x - 0.2, aa, width=0.4, label='AA')
            ax.bar(x + 0.2, fm, width=0.4, label='FM')
            ax.set_xticks(x)
            ax.set_xticklabels(names, rotation=30, ha='right')
            ax.set_ylim(0, 1.05)
            ax.set_ylabel('score')
            ax.set_title('Continual learning: Average Accuracy and Forgetting Measure')
            ax.legend()
            fig.tight_layout()
            fig.savefig(os.path.join(OUT, 'continual_comparison.png'), dpi=150)
            plt.close(fig)

        # Stream deltas
        if "hsam_stream" in summary:
            modes = list(summary["hsam_stream"].keys())
            deltas = [summary["hsam_stream"][m]['delta']['mean'] for m in modes]
            fig, ax = plt.subplots(figsize=(6,4))
            ax.bar(modes, deltas)
            ax.axhline(0, color='black', linewidth=0.8)
            ax.set_ylabel('delta acc (last-first)')
            ax.set_title('HSAM stream probe deltas')
            fig.tight_layout()
            fig.savefig(os.path.join(OUT, 'stream_deltas.png'), dpi=150)
            plt.close(fig)
    except Exception as e:
        with open(os.path.join(OUT, "plot_error.txt"), "w", encoding="utf-8") as f:
            f.write(str(e))

    print("wrote", OUT)


if __name__ == "__main__":
    main()
